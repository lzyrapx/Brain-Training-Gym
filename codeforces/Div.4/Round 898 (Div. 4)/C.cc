void solve() {
    int n = 10;
    int ans = 0;
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
            char c;
            cin >> c;
            if (c == 'X') {
                ans += min(min(i + 1, n - i), min(j + 1, n - j));
            }
        }
    }
    cout << ans << "\n";
}

